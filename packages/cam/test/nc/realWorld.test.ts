const moves = (program: NcProgram): ToolpathMove[] =>
    program.toolpaths.flatMap((path) => path.toolpath.moves).filter((move) => move.kind !== "comment");
const warnings = (program: NcProgram) =>
    program.diagnostics.filter((d) => d.severity !== "info").map((d) => d.message);

