describe("real-world programs", () => {
    test("a Fusion-style Fanuc program: tools from the header, labels, cycles, stops, reference moves", () => {
        const program = readNcProgram(FUSION_FANUC);
        expect(program.dialect).toBe("fanuc");
        expect(program.detected).toBe(true);
        expect(program.programNumber).toBe("1001");
        expect(program.name).toBe("BRACKET");
        expect(program.tools.map((tool) => [tool.number, tool.diameter])).toEqual([
            [1, 10],
            [2, 6.8],
        ]);
        expect(program.toolpaths.map((path) => [path.toolNumber, path.toolpath.label])).toEqual([
            [1, "2D CONTOUR1"],
            [2, "DRILL1"],
        ]);
        const all = moves(program);
        expect(all.filter((move) => move.kind === "arc")).toHaveLength(2);
        expect(
            all.filter((move) => move.kind === "drill").map((move) => (move.kind === "drill" ? move.at : [])),
        ).toEqual([
            [20, 20, 5],
            [40, 20, 5],
        ]);
        // M1 before the tool change is an (optional) stop.
        expect(all.some((move) => move.kind === "dwell" && move.seconds === 0)).toBe(true);
        expect(warnings(program)).toEqual([]);
        // G53 G0 Z0. returns to the reference height, drawn at the highest programmed Z (where
        // the program already is); X/Y homing is reported, not drawn.
        expect(program.stats.bounds?.max[2]).toBe(15);
        expect(program.diagnostics.map((d) => d.message)).toContain(
            "X/Y reference positions are unknown in the work offset: X and Y are left where they are",
        );
        expect(program.stats.cutBounds).toEqual({ min: [-5.5, -5.5, -20], max: [60, 50, 5] });
    });

    test("a Mastercam-style inch program: leading-dot numbers, R arcs, G28 in two steps", () => {
        const program = readNcProgram(MASTERCAM_INCH);
        expect(program.units).toBe("inch");
        const arc = moves(program).find((move) => move.kind === "arc") as Extract<
            ToolpathMove,
            { kind: "arc" }
        >;
        expect(arc.to[0]).toBeCloseTo(1.75 * 25.4, 9);
        expect(arc.center[0]).toBeCloseTo(1.75 * 25.4, 9);
        expect(arc.center[1]).toBeCloseTo(0, 9);
        expect(arc.feed).toBeCloseTo(20 * 25.4, 9);
        expect(program.toolpaths[0].toolpath.spindleRpm).toBe(5000);
        expect(warnings(program)).toEqual([]);
    });

    test("LinuxCNC: named parameters, o-word subroutine called in a while loop", () => {
        const program = readNcProgram(LINUXCNC_SUBS);
        expect(program.dialect).toBe("linuxcnc");
        const plunges = moves(program).filter((move) => move.kind === "linear");
        expect(plunges).toHaveLength(4);
        const round = (value: number) => Math.round(value) + 0;
        const holes = plunges.map((move) =>
            "to" in move ? [round(move.to[0]), round(move.to[1]), move.to[2]] : [],
        );
        expect(holes).toEqual([
            [20, 0, -3],
            [0, 20, -3],
            [-20, 0, -3],
            [0, -20, -3],
        ]);
        expect(program.toolpaths[0].toolNumber).toBe(3);
        expect(warnings(program)).toEqual([]);
    });

    test("GRBL from a hobby CAM: packed words, no tool changer", () => {
        const program = readNcProgram(GRBL_HOBBY);
        expect(program.dialect).toBe("grbl");
        // G0X0Y0 after G0Z5 from an unknown start lands where the first rapid assumed (X0 Y0).
        expect(moves(program).map((move) => move.kind)).toEqual([
            "rapid",
            "linear",
            "linear",
            "arc",
            "linear",
            "rapid",
        ]);
        expect(program.toolpaths[0].toolNumber).toBe(0);
        expect(program.stats.spindle).toEqual({ min: 18000, max: 18000 });
        expect(warnings(program)).toEqual([]);
    });

    test("Siemens: CR= radius, AC() centres, G4 F seconds, MSG", () => {
        const program = readNcProgram(SIEMENS_ISO);
        expect(program.dialect).toBe("siemens");
        const arcs = moves(program).filter((move) => move.kind === "arc") as Extract<
            ToolpathMove,
            { kind: "arc" }
        >[];
        expect(arcs.map((arc) => [arc.center[0], arc.center[1], arc.clockwise])).toEqual([
            // CR > 0: the short way round, clockwise from (10, 0) to (20, 10).
            [expect.closeTo(20, 9), expect.closeTo(0, 9), true],
            [30, 10, false],
        ]);
        expect(moves(program)).toContainEqual({ kind: "dwell", seconds: 1.5 });
        expect(program.toolpaths[0].toolpath.moves).toContainEqual({ kind: "comment", text: "ROUGHING" });
        expect(warnings(program)).toEqual([]);
    });

    test("PrusaSlicer output: firmware codes ignored, extrusion and layers read", () => {
        const program = readNcProgram(PRUSASLICER);
        expect(program.dialect).toBe("prusa");
        expect(program.machineKind).toBe("printer");
        expect(program.stats.layers).toBe(2);
        expect(program.stats.filament).toBeCloseTo(2 + 9 - 0.8 + 0.8 + 0.03345 + 0.04 + 0.05 + 0.04, 6);
        expect(warnings(program)).toEqual([]);
        // The arc with extrusion is drawn as extruding segments.
        const extrudes = moves(program).filter((move) => move.kind === "extrude");
        expect(extrudes.length).toBeGreaterThan(8);
    });
});

describe("statistics", () => {
    const machine: MachineProfileData = {
        id: "m",
        name: "Mill",
        kind: "mill",
        linearAxes: [],
        maxFeed: 600,
        rapidFeed: 6000,
        post: { id: "fanuc" },
    };

    test("lengths at their true length, times at the machine's limits", () => {
        const program = readNcProgram(
            ["G0 X0 Y0 Z10", "G0 Z0", "G1 X100 F1200", "G3 X100 Y20 I0 J10", "G4 P2000", "G0 Z10"].join("\n"),
            { machine },
        );
        const { stats } = program;
        expect(stats.rapidLength).toBeCloseTo(20, 9);
        expect(stats.cuttingLength).toBeCloseTo(100 + Math.PI * 10, 9);
        // Feeds capped at the machine's 600 mm/min, rapids at 6000.
        expect(stats.cuttingTime).toBeCloseTo(((100 + Math.PI * 10) / 600) * 60, 9);
        expect(stats.rapidTime).toBeCloseTo((20 / 6000) * 60, 9);
        expect(stats.dwellTime).toBe(2);
        expect(stats.totalTime).toBeCloseTo(stats.cuttingTime + stats.rapidTime + 2, 9);
        expect(stats.timeAssumed).toBe(false);
        // The arc bulges to X110: bounds follow arcs, not only their end points.
        expect(stats.bounds).toEqual({ min: [0, 0, 0], max: [110, 20, 10] });
        expect(stats.feed).toEqual({ min: 1200, max: 1200 });
    });
});
