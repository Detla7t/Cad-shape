/**
 * A toolpath with a new tool as a manual-change program says it: retract to the program's
 * clearance height (the post's way without a Z home), then a stop.
 */
function stopAtToolChange(path: ToolpathData, index: number, paths: readonly ToolpathData[]): ToolpathData {
    if (index === 0 || paths[index - 1].toolId === path.toolId) return path;
    const last = paths[index - 1].moves
        .map(moveEnd)
        .filter((end) => end !== undefined)
        .at(-1)!;
    const clearance = clearanceHeight(paths);
    return {
        ...path,
        moves: [
            { kind: "rapid", to: [last[0], last[1], Math.max(last[2], clearance)] },
            { kind: "dwell", seconds: 0 },
            ...path.moves,
        ],
    };
}

function readBack(text: string, postId: string, machine?: MachineProfileData): NcProgram {
    const program = readNcProgram(text, {
        dialect: dialectOfPost(postId),
        ...(machine === undefined ? {} : { machine }),
    });
    const errors = program.diagnostics.filter((d) => d.severity === "error");
    expect(errors).toEqual([]);
    return program;
}

describe("round trip through the mill posts", () => {
    const millPosts = postProcessors("mill").filter((p) =>
        ["fanuc", "haas", "linuxcnc", "mach3", "grbl"].includes(p.id),
    );

    test("every 3-axis mill post is covered", () => {
        expect(millPosts.map((p) => p.id).sort()).toEqual(["fanuc", "grbl", "haas", "linuxcnc", "mach3"]);
    });

    const cases = millPosts.flatMap((p) =>
        [
            {},
            { arcs: "r" },
            { arcs: "linear" },
            { cannedCycles: false },
            { lineNumbers: true, comments: false },
        ].map((options) => [p.id, options] as const),
    );

    test.each(cases)("%s %j", (postId, options) => {
        const text = post(postId, MILL_PROGRAM, options);
        expect(detectNcDialect(text)).toBe(dialectOfPost(postId));
        const read = readBack(text, postId);
        // GRBL has no tool changer: a change is a stop (M0) after a "Tool change: Tn" comment, so
        // without comments it is only the stop, and the tool in the spindle is never named (0).
        const manual = postId === "grbl";
        const silent = manual && "comments" in options && options.comments === false;
        const expectedPaths = silent ? MILL_PATHS.map(stopAtToolChange) : MILL_PATHS;
        // R-format arcs near a half circle put the centre within ~0.01 of where it was (R has 3–4 decimals).
        expectSameToolpaths(
            expectedPaths,
            read,
            "arcs" in options && options.arcs === "r" ? { tolerance: 0.01 } : {},
        );
        const expectedTools = silent ? [0] : manual ? [0, ...MILL_TOOLS.slice(1)] : MILL_TOOLS;
        expect(toolSequence(read.toolpaths.map((path) => path.toolNumber))).toEqual(expectedTools);
        expect(read.units).toBe("mm");
        expect(read.stats.cuttingLength).toBeGreaterThan(100);
    });

    test("drilling cycles come back as drill moves where the control runs them", () => {
        const read = readBack(post("fanuc", MILL_PROGRAM), "fanuc");
        const drills = read.toolpaths
            .flatMap((path) => path.toolpath.moves)
            .filter((move) => move.kind === "drill");
        expect(drills.map((move) => move.cycle)).toEqual([
            "drill",
            "drill",
            "drill",
            "peck",
            "chipBreak",
            "bore",
            "tap",
            "tap",
        ]);
        // The hole top is the R plane: the program does not say where material starts.
        expect(drills[3]).toEqual({
            kind: "drill",
            at: [40, -20, 2],
            depth: 14,
            retract: 2,
            cycle: "peck",
            peck: 3,
            feed: 150,
        });
    });

    test("spindle speeds and coolant follow each tool", () => {
        const read = readBack(post("haas", MILL_PROGRAM), "haas");
        expect(
            read.toolpaths.map((path) => [path.toolNumber, path.toolpath.spindleRpm, path.toolpath.coolant]),
        ).toEqual([
            [1, 10000, "flood"],
            [4, 15000, "mist"],
            [2, 2000, "flood"],
            [3, 500, undefined],
        ]);
        expect(read.stats.spindle).toEqual({ min: 500, max: 15000 });
        expect(read.stats.tools).toEqual([1, 4, 2, 3]);
        expect(read.stats.toolChanges).toBe(3);
    });
});

