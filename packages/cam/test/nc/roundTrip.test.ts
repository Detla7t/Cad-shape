/**
 * Conformance by round trip: toolpaths — generated by the CAM operations or built by hand —
 * posted with every registered post, read back with the NC reader, and compared move for
 * move (see `_helpers/ncRoundTrip.ts`): arcs and helices, drilling cycles canned or
 * expanded, tool changes, dwells and stops, 5-axis tool axes through each machine's
 * kinematics, beam on/off with pierce delays, wire tapers, extrusion.
 */

const SETUP: SetupData = {
    id: "s1",
    name: "Setup 1",
    machineId: "test",
    wcs: { origin: [0, 0, 0], xAxis: [1, 0, 0], zAxis: [0, 0, 1] },
    stock: { kind: "box", margin: { x: 1, y: 1, zTop: 1, zBottom: 0 } },
    partIds: [],
    operations: [],
};

function camProgram(machine: MachineProfileData, toolpaths: ToolpathData[], tools: ToolData[]): CamProgram {
    return {
        name: "Part",
        machine,
        setup: SETUP,
        tools: new Map(tools.map((tool) => [tool.id, tool])),
        toolpaths,
    };
}

function ok<T>(result: { isOk: boolean; value?: T; error?: string } | Promise<unknown>): T {
    if (!("isOk" in result)) throw new Error("expected a synchronous result");
    if (!result.isOk) throw new Error(result.error);
    return result.value as T;
}

function post(id: string, program: CamProgram, options?: Record<string, unknown>): string {
    const processor = postProcessor(id);
    expect(processor).not.toBeUndefined();
    return ok(processor!.post(program, options));
}

