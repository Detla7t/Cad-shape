const SHEET = {
    min: [-50, -50, -6] as [number, number, number],
    max: [250, 150, 0] as [number, number, number],
};

function cuttingPaths(kind: "plasma" | "waterjet" | "laser"): {
    machine: MachineProfileData;
    paths: ToolpathData[];
    tool: ToolData;
} {
    const tool: ToolData = {
        id: "jet",
        number: 1,
        name: "Jet",
        kind: "jet",
        diameter: 1.5,
        cutting: { feed: 3000 },
    };
    const context = fakeContext({
        machine: { kind, cutting: { kerf: 1.5, pierceDelay: 0.5, pierceHeight: 3.8, cutHeight: 1.5 } },
        tool,
        loops: [
            { points: rectLoop(0, 0, 80, 50), closed: true, role: "sketch", z: 0 },
            { points: circleLoop([40, 25], 10, 0.001, false), closed: true, role: "sketch", z: 0 },
        ],
        stock: SHEET,
        setupStock: { kind: "sheet", width: 300, height: 200, thickness: 6 },
    });
    const path = ok<ToolpathData>(profileCutOperation.generate(operation("profileCut", {}), context));
    return { machine: context.machine, paths: [{ ...path, label: "Profile" }], tool };
}

describe("round trip through the cutting posts", () => {
    const posts = postProcessors().filter((p) =>
        p.machineKinds.some((kind) => ["plasma", "waterjet", "laser"].includes(kind)),
    );

    test("every cutting post is covered", () => {
        expect(posts.map((p) => p.id).sort()).toEqual(["laser-generic", "laser-grbl", "plasma", "waterjet"]);
    });

    test.each(
        posts.flatMap((p) => [[p.id, false] as const, [p.id, true] as const]),
    )("%s (Z out: %s)", (postId, outputZ) => {
        const kind = postProcessor(postId)!.machineKinds[0] as "plasma" | "waterjet" | "laser";
        const { machine, paths, tool } = cuttingPaths(kind);
        const text = post(postId, camProgram(machine, paths, [tool]), { outputZ });
        const read = readBack(text, postId, machine);
        expectSameToolpaths(paths, read, { xyOnly: !outputZ });
        const ons = read.toolpaths
            .flatMap((path) => path.toolpath.moves)
            .filter((move) => move.kind === "cutterOn");
        expect(ons.length).toBe(2);
        // The pierce delay (G4 after the beam comes on) is the cutterOn's.
        expect(ons.every((move) => move.kind === "cutterOn" && move.pierceDelay === 0.5)).toBe(true);
    });

    test.each(posts.map((p) => p.id))("%s output is recognized as its dialect", (postId) => {
        const kind = postProcessor(postId)!.machineKinds[0] as "plasma" | "waterjet" | "laser";
        const { machine, paths, tool } = cuttingPaths(kind);
        expect(detectNcDialect(post(postId, camProgram(machine, paths, [tool])))).toBe(dialectOfPost(postId));
    });
});

