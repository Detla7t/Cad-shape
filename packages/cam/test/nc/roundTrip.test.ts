describe("round trip through the 5-axis posts", () => {
    const fiveAxis = postProcessors("mill").filter(
        (p) => !["fanuc", "haas", "linuxcnc", "mach3", "grbl"].includes(p.id),
    );

    test("every 5-axis post is covered", () => {
        expect(fiveAxis.map((p) => p.id).sort()).toEqual([
            "fanuc-30i-5axis",
            "generic-5axis-nontcp",
            "haas-umc-5axis",
            "heidenhain-tnc-5axis",
            "siemens-840d-5axis",
        ]);
    });

    test.each([
        ["fanuc-30i-5axis", GENERIC_AC_TRUNNION, {}, {}],
        ["fanuc-30i-5axis", GENERIC_CA_HEAD_HEAD, {}, {}],
        ["fanuc-30i-5axis", GENERIC_BC_HEAD_TABLE, {}, {}],
        ["haas-umc-5axis", GENERIC_AC_TRUNNION, {}, {}],
        ["siemens-840d-5axis", GENERIC_AC_TRUNNION, {}, {}],
        ["siemens-840d-5axis", GENERIC_CA_HEAD_HEAD, {}, {}],
        ["siemens-840d-5axis", GENERIC_CA_HEAD_HEAD, { orientation: "vector" }, {}],
        [
            "generic-5axis-nontcp",
            GENERIC_AC_TRUNNION_NON_TCP,
            { tolerance: 0.05, maxAngleStep: 30 },
            { ignoreFeed: true, tolerance: 0.06 },
        ],
    ] as const)("%s on %s", (postId, machine, options, compare: RoundTripOptions) => {
        const program = fiveAxisProgram(machine);
        const text = post(postId, program, options);
        expect(detectNcDialect(text)).toBe(dialectOfPost(postId));
        const read = readBack(text, postId, machine);
        expectSameToolpaths(program.toolpaths, read, { tolerance: 0.002, ...compare });
        const axes = read.toolpaths
            .flatMap((path) => path.toolpath.moves)
            .filter((move) => "axis" in move && move.axis !== undefined);
        expect(axes.length).toBeGreaterThan(3);
    });

    test("Heidenhain conversational is recognized and refused", () => {
        const text = post("heidenhain-tnc-5axis", fiveAxisProgram(GENERIC_BC_HEAD_TABLE));
        expect(detectNcDialect(text)).toBe("heidenhain");
        const read = readNcProgram(text);
        expect(read.dialect).toBe("heidenhain");
        expect(read.toolpaths).toEqual([]);
        expect(read.diagnostics).toEqual([
            expect.objectContaining({ severity: "error", message: expect.stringContaining("not supported") }),
        ]);
    });

    test("without a machine profile rotary words are reported and the tool stays vertical", () => {
        const text = post("fanuc-30i-5axis", fiveAxisProgram(GENERIC_AC_TRUNNION));
        const read = readNcProgram(text);
        expect(read.diagnostics.map((d) => d.message)).toEqual(
            expect.arrayContaining([expect.stringContaining("without a machine profile")]),
        );
        const tilted = read.toolpaths
            .flatMap((path) => path.toolpath.moves)
            .filter((move) => "axis" in move && move.axis !== undefined);
        // Only the tilted plane (G68.2 + G53.1) still orients the tool: the plane says so itself.
        expect(tilted.every((move) => "axis" in move && Math.abs(move.axis![1] - 0.5) < 1e-3)).toBe(true);
    });
});

