/**
 * Reference data for the function browser: an Excel-style category, a signature, a
 * one-line description, an example and argument notes for (far) more functions than the
 * engine evaluates. `functionInfo.ts` merges it with the evaluator's own metadata; the
 * browser lists only names in `FORMULA_FUNCTIONS`, so an entry here never advertises an
 * unsupported function. Pure data: no imports, so any module may use it without cycles.
 */

