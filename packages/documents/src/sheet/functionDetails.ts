/** [signature, description, example, argument notes by parameter name (digits and brackets stripped)]. */
type Row = readonly [signature: string, description: string, example: string, args?: Record<string, string>];

export interface FunctionDetail {
    category: FunctionCategory;
    signature: string;
    description: string;
    example: string;
    args?: Record<string, string>;
}

